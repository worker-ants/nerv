-- 이미 있는 계정은 확인된 것으로 둔다 (2026-09-22 · 사람 승인 · scope.md §2.1)
--
-- **가입 이메일 인증을 강제하기로 했다.** 그런데 `user.email_verified` 의 기본값은 `false` 이고
-- 지금 있는 계정은 아무도 확인 절차를 거친 적이 없다 — 그대로 켜면 **기존 사용자가 전부
-- 잠긴다.** 새 규칙을 과거에 소급하는 셈이고, 그 대가를 치르는 사람은 아무 잘못도 하지 않았다.
--
-- 그래서 이 마이그레이션이 도는 **시점까지 존재하던 계정**만 확인 처리한다. 이후에 가입하는
-- 사람은 기본값 `false` 로 들어와 메일을 받는다 — 규칙은 오늘부터 적용된다.
--
-- **되돌릴 수 없다는 것을 적어 둔다.** 여기서 참으로 바꾼 행은 "그 주소가 그 사람의 것인지
-- 물어본 적이 없는" 행이다. 그 사실이 중요해지는 날(예: 발신 도메인 평판) 다시 물을 수는
-- 있지만, 이 마이그레이션이 무엇을 했는지는 이 주석이 유일한 기록이다.
UPDATE "user" SET email_verified = true WHERE email_verified = false;
