-- 우선순위 미표기를 NULL 로 적을 수 있게 한다 (2026-09-06 · importer.md §2.5 규칙 4)
--
-- 규칙은 "미표기는 NULL 로 두고 추정하지 않는다" 였는데 열이 NOT NULL 이라 **적을 수가
-- 없었다.** 그래서 임포터는 전건 `must` 를 넣고 있었다 — 원본에 우선순위가 적힌 적 없는
-- 요구사항이 저장에서 "필수" 가 됐고, 뒤에 오는 사람은 그것을 원본의 선언으로 읽는다.
-- 리포트 규칙 `req-priority-missing`(class manual)도 같은 이유로 발생할 수 없었다.
--
-- NULL 은 `must` 의 축약이 아니라 **표기가 없었다는 사실**이다. 모르는 것을 아는 척
-- 채우지 않는다 — 0019 가 `manual` 을 소급 변환하지 않은 것과 같은 판단이고,
-- `--owner-map` 에 없는 owner 를 추정 배정하지 않는 REQ-IMP-008 과 같은 원칙이다.
--
-- 기존 행에는 영향이 없다. 제약을 푸는 방향이라 되돌리기도 (값이 다 차 있는 동안은) 쉽다.
ALTER TABLE "requirement" ALTER COLUMN "priority" DROP NOT NULL;
