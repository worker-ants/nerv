-- 계획의 우선순위 미표기를 NULL 로 적을 수 있게 한다 (2026-09-07 · importer.md §2.6)
--
-- 0020 이 요구사항에서 한 판단과 같다. 원본 계획 문서는 우선순위를 적지 않는데 열이
-- `NOT NULL DEFAULT 'P2'` 라, 임포터는 481건을 전부 `P2` 로 적재했다 — 그리고 보드는
-- 그것을 **사람이 고른 값**으로 그린다. 뒤에 오는 사람은 저장된 값을 원본의 선언으로
-- 읽으므로, 지어 넣은 기본값은 조용한 거짓이 된다.
--
-- NULL 은 `P2` 의 축약이 아니라 **표기가 없었다는 사실**이다. 정렬에서는 뒤로 보낸다
-- (`NULLS LAST`) — 고르지 않은 것이 고른 것보다 앞에 설 이유가 없다.
--
-- 기존 행에는 영향이 없다(제약을 푸는 방향). 이미 `P2` 로 적재된 임포트분을 NULL 로
-- 되돌리는 것은 이 마이그레이션의 일이 아니다 — 무엇이 임포트분인지는 매니페스트가
-- 알고, 그 백필은 사람이 판단해 한 번 돌린다.
ALTER TABLE "task" ALTER COLUMN "priority" DROP NOT NULL;
